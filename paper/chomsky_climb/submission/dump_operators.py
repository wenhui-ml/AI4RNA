#!/usr/bin/env python3
"""Dump the six agent-written operator sources out of the invention logs into readable .py files.

Nothing is missing from the supplement here: `best_code` in each `invent_operator/*/result.json`
already carries the full source, all six models included. This exists because the two operators that
carry the paper's one positive result are the artifact a reviewer is most likely to want to *read*, and
right now reading them means writing a JSON extractor first.

Runs anywhere, needs nothing installed:

    cd <repo root>
    python3 paper/chomsky_climb/submission/dump_operators.py

Writes rna_harness/runs/cc_ascent/invent_operator/<slug>/operator.py, which build.sh stage 2 already
rsyncs. Emitted files are byte-identical to `best_code` plus a provenance header, so they cannot drift
from the JSON the numbers were computed from.
"""
import glob
import json
import os
import sys

BASE = os.path.join("rna_harness", "runs", "cc_ascent", "invent_operator")
if not os.path.isdir(BASE):
    sys.exit(f"ABORT: {BASE} not found. Run this from the repo root.")

# The six invention draws: five in per-model subdirectories, plus the original GLM-5.2 draw at the root
# of invent_operator/. That root file is easy to miss and is one of the six.
paths = sorted(glob.glob(os.path.join(BASE, "*", "result.json")))
root = os.path.join(BASE, "result.json")
if os.path.exists(root):
    paths.append(root)

n = 0
for p in paths:
    d = json.load(open(p))
    code = d.get("best_code")
    if not code:
        print(f"   SKIP {p}: no best_code")
        continue
    if "def design(" not in code:
        print(f"   WARNING {p}: best_code has no design() entry point")
    out = os.path.join(os.path.dirname(p), "operator.py")
    header = (
        '"""Frozen agent-written operator, extracted verbatim from result.json["best_code"].\n\n'
        f'model            {d["model"]}\n'
        f'best round       {d["best_round"]} of {len(d.get("rounds", []))}\n'
        f'train solved     {d.get("best_train_solved")}\n'
        f'held out         pKiss {d.get("heldout_pkiss")}, ProbKnot {d.get("heldout_probknot")}, '
        f'pKiss AND ProbKnot {d.get("heldout_pk_and_pb")}, panel-unanimous {d.get("heldout_panel_unanimous")}\n\n'
        "GENERATED by submission/dump_operators.py -- do not edit. The measurements in the paper\n"
        "re-execute this source; result.json remains the authority if the two ever disagree.\n"
        '"""\n'
    )
    open(out, "w").write(header + code)
    n += 1
    print(f"   {os.path.relpath(out):68} {len(code):>6} chars  {d['model']}")

print(f"\n   wrote {n} operator sources (expected 6)")
if n != 6:
    print("   WARNING: the paper reports six invention draws. Check for a missing result.json.")
