#!/usr/bin/env python3
"""Emit the claim index: every headline number in the manuscript, the script that produced it, and the
committed output file a reviewer can open to check it.

Why this is a rebuttal artifact and not documentation. The single most expensive kind of rebuttal question is
"where does this number come from?", and the single most damaging answer is a delay. This table answers it in
one hop for every number a reviewer is likely to challenge, and because it is generated rather than typed it
cannot drift from the manuscript the way a hand-kept list does.

The index is DECLARED here and VERIFIED against two things at generation time: the number must still appear in
chomsky_climb.tex, and the named output file must exist. A row that fails either check is emitted with a
FAIL marker rather than silently dropped, because a quietly missing row is exactly the failure this file is
meant to prevent.
"""
import os, re, sys

