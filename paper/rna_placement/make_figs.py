#!/usr/bin/env python3
"""Every figure in the paper, emitted as TikZ/pgfplots from the committed JSON.

The figures are .tex fragments the manuscript \\input{}s: native vector graphics in the
document's own fonts, diffable in review, and with every coordinate generated rather than typed.
The provenance rule that governs the prose governs the figures -- no number is hand-copied.

make_figs_mpl_reference.py is the previous matplotlib emitter, kept so the two renderings of the
same artifacts can be compared. It is not part of the build.

Palette: blue #2a78d6, orange #eb6834, aqua #1baf7a, unchanged from the reference implementation,
declared in the manuscript preamble as rpBlue / rpOrange / rpAqua.

COST: $0, offline.
"""
from __future__ import annotations
import json, os, sys

import numpy as np

CEIL = "/data/wenhui/openclaude_rna/rna_harness/runs/ceiling"
OUT = os.path.dirname(os.path.abspath(__file__)) + "/figs"
S1, S2, S3 = "rpBlue", "rpOrange", "rpAqua"
INK, INK2, INK3 = "rpInk", "rpInkB", "rpInkC"
CEILING = 0.6956

EN = {"样本2(主)": "sample 2 (main)", "基准4560": "baseline 4560", "样本3": "sample 3",
      "第四批": "batch 4", "第五批(盲)": "batch 5", "第六批(盲)": "batch 6"}
POPNAME = [EN[n] for n in ("样本2(主)", "基准4560", "样本3", "第四批", "第五批(盲)", "第六批(盲)")]
# The artifacts key the six populations by the internal file they were built from, and the
# correspondence is fixed by the runs (c1_width_null.py, ceiling_probe.py). Figure 2 was
# printing those file nicknames -- "fresh", "designs", "third" -- while every other figure
# and table in the paper printed the population names, so the same six rows carried two
# different sets of labels. One map, and a check that the artifact still agrees with it.
POPFILE = ["panel_f1_fresh.json", "panel_f1_designs.json", "panel_f1_third.json",
           "panel_f1_fourth.json", "panel_f1_fifth.json", "panel_f1_sixth.json"]
POPBY = dict(zip(POPFILE, POPNAME))


def popnames(keys):
    ks = list(keys)
    if ks != POPFILE:
        raise SystemExit(f"population set changed: {ks} != {POPFILE}; the labels in this "
                         "figure are read from POPBY and would be wrong")
    return [POPBY[k] for k in ks]


def popnames_subset(keys):
    """Same map, for an artifact that covers only some of the populations.

    r1b only has the four with repeat groups. A SUBSET is legitimate; an unknown key is not,
    and would silently print an internal filename as a population name.
    """
    ks = list(keys)
    unknown = [k for k in ks if k not in POPBY]
    if unknown:
        raise SystemExit(f"unknown population key(s) {unknown}; POPBY holds {POPFILE}")
    return [POPBY[k] for k in ks]

BASE = (r"axis lines=left, axis line style={line width=0.5pt, color=" + INK3 + r"},"
        "\n    tick style={line width=0.5pt, color=" + INK3 + r"}, tick align=outside,"
        "\n    label style={font=\\scriptsize, color=" + INK2 + r"},"
        "\n    tick label style={font=\\tiny, color=" + INK2 + r"},"
        "\n    legend style={font=\\tiny, draw=none, fill=none, text=" + INK2 + r"},"
        "\n    clip=false, scaled x ticks=false, scaled y ticks=false,"
        "\n    /pgf/number format/fixed, /pgf/number format/precision=3,"
        "\n    /pgf/number format/1000 sep={},"
        "\n    title style={font=\\scriptsize, color=" + INK + r", at={(0,1.03)}, anchor=south west}")


def en(n):
    return EN.get(n, n)


def pv(x):
    """a permutation p of 0 is the floor of the null, not a measured zero."""
    return r"<10^{-3}" if float(x) < 1e-4 else f"{float(x):.4f}"


def esc(t):
    """LaTeX-escape a label. Tick labels are typeset in text mode, so a filename with an
    underscore is a compile error rather than a cosmetic problem."""
    return (str(t).replace("\\", "").replace("_", r"\_")
            .replace("%", r"\%").replace("&", r"\&").replace("#", r"\#"))


def popname(k):
    """m17d keys its populations by source filename; make them readable."""
    return esc(str(k).replace("panel_f1_", "").replace(".json", ""))


def J(name):
    return json.load(open(os.path.join(CEIL, name)))


def emit(name, body):
    with open(os.path.join(OUT, name), "w") as fh:
        fh.write("% GENERATED by make_figs.py from rna_harness/runs/ceiling/*.json.\n"
                 "% Do not edit: every coordinate below comes from a committed run artifact.\n")
        fh.write(body.rstrip() + "\n")
    print(f"  wrote figs/{name}")


def co(xs, ys):
    return " ".join(f"({x},{y})" for x, y in zip(xs, ys))


def pic(body):
    return "\\begin{tikzpicture}\n" + body.rstrip() + "\n\\end{tikzpicture}"


def grp(n, body, hsep="1.5cm"):
    return pic(r"\begin{groupplot}[group style={group size=" + f"{n} by 1, horizontal sep={hsep}"
               + r"}, " + BASE + "]\n" + body.rstrip() + "\n" + r"\end{groupplot}")


def iv(lo, hi, y, col, lw="1.4pt"):
    return (rf"\addplot[color={col}, line width={lw}, forget plot] "
            rf"coordinates {{({lo},{y}) ({hi},{y})}};")


def pt(x, y, col, ms="2.2pt", mark="*"):
    return (rf"\addplot[color={col}, mark={mark}, mark size={ms}, only marks, forget plot] "
            rf"coordinates {{({x},{y})}};")


def zeroline(y0, y1):
    """a vertical rule at zero, drawn with \\draw rather than \\addplot.

    An extra tick's grid inherits the current plot cycle's colour; and inside an xbar axis every
    \\addplot is rendered as a bar, so a two-point "line" comes out as a pair of stubs in the next
    cycle colour. Both mistakes were made and both are visible only by looking at the figure."""
    return (rf"\draw[color={INK3}, densely dotted, line width=0.6pt] "
            rf"(axis cs:0,{y0}) -- (axis cs:0,{y1});")


def band(x0, x1, y0, y1, col=INK3, op="0.28"):
    return (rf"\fill[{col}, opacity={op}] (axis cs:{x0},{y0}) rectangle (axis cs:{x1},{y1});")


def ylabels(names):
    ticks = ",".join(str(len(names) - i) for i in range(len(names)))
    labs = ",".join("{" + n + "}" for n in names)
    return ticks, labs


# ---------------------------------------------------------------- fig 3: matched pairs vs null
def fig3():
    d = J("m18_repaired_null.json")["pops"]
    rows = []
    for nm, r in zip(popnames(d), d.values()):
        b = r["arms"]["B_panel_matched"]
        rows.append((nm, b, b["usable"]))
    L, names = [], []
    for k, (nm, a, us) in enumerate(rows):
        y = len(rows) - k
        sd = a["null_sd"]
        L.append(band(-1.96 * sd, 1.96 * sd, y - 0.30, y + 0.30))
        c = S1 if us else S3
        L.append(iv(a["boot_ci_secondary"][0], a["boot_ci_secondary"][1], y, c, "1.0pt"))
        L.append(pt(a["effect"], y, c, "2.4pt"))
        z, p = a["z_vs_null_REPAIRED"], a["p_perm_REPAIRED"]
        txt = f"{a['effect']:+.2f}  z={z:.1f}" + ("" if p <= .005 else f"  p={p:.3f}")
        L.append(rf"\node[font=\tiny, color={INK2}, right] at "
                 rf"(axis cs:{a['boot_ci_secondary'][1] + .15},{y}) {{{txt}}};")
        names.append(en(nm) + ("" if us else " (n.u.)"))
    ticks, labs = ylabels(names)
    # xmin was fixed at -1.2 while batch 6's null band reaches -4.03, so that band was drawn
    # outside the axis and ran underneath the population names. The band is the comparison
    # object; it is the axis that has to make room for it, not the band that gets clipped.
    xlo = 1.06 * min(min(-1.96 * a["null_sd"], a["boot_ci_secondary"][0]) for _n, a, _u in rows)
    body = rf"""\begin{{axis}}[width=11.0cm, height=6.0cm, {BASE},
    xlabel={{matched-pair difference (OpenKnot points)}},
    xmin={xlo:.2f}, xmax=9.6, ymin=0.4, ymax={len(rows)+0.6},
    ytick={{{ticks}}}, yticklabels={{{labs}}},]
{chr(10).join(L)}
\end{{axis}}
\node[font=\tiny, color={INK2}, anchor=north] at (current bounding box.south)
  {{\tikz\fill[{INK3}, opacity=0.28] (0,0) rectangle (0.32,0.16);\ permutation null $\pm$1.96\,SD
   \quad \textcolor{{{S1}}}{{$\bullet$}} usable
   \quad \textcolor{{{S3}}}{{$\bullet$}} not usable}};"""
    emit("fig3_matched.tex", pic(body))


