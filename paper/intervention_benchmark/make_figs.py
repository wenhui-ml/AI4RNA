#!/usr/bin/env python3
"""Display items for the intervention-benchmark manuscript, emitted as TikZ/pgfplots.

Each figure is written as a .tex fragment the manuscript \\input{}s, so the figures are native
vector graphics in the document's own fonts. The numbers inside them are still generated: every
coordinate below comes from a committed run artifact, exactly as \\jdg{} does for the prose.
Nothing is recomputed here -- when a curve is needed and no artifact holds it, the run that
produces it is written and committed first, which is why m31t_recovery_curve.json exists.
"""
from __future__ import annotations

import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
CEIL = os.path.abspath(os.path.join(HERE, "..", "..", "rna_harness", "runs", "ceiling"))
FIGS = os.path.join(HERE, "figs")
os.makedirs(FIGS, exist_ok=True)

NEU, THM, FREE, INK, GREY, MID = ("nmneural", "nmthermo", "nmfree", "nmink", "nmgrey", "nmmid")

COMMON = r"""axis lines=left, axis line style={line width=0.4pt},
    clip=false, scaled x ticks=false, scaled y ticks=false,
    /pgf/number format/fixed, /pgf/number format/precision=3,
    tick style={line width=0.4pt, color=nmgrey}, tick align=outside,
    label style={font=\footnotesize}, tick label style={font=\scriptsize},
    legend style={font=\scriptsize, draw=none, fill=none},
    title style={font=\footnotesize\bfseries, at={(0,1.02)}, anchor=south west}"""


def J(n):
    return json.load(open(os.path.join(CEIL, n)))


def emit(name, body):
    with open(os.path.join(FIGS, name), "w") as fh:
        fh.write("% GENERATED by make_figs.py from rna_harness/runs/ceiling/*.json.\n"
                 "% Do not edit: every coordinate below comes from a committed run artifact.\n")
        fh.write(body.rstrip() + "\n")
    print(f"  wrote figs/{name}")


def co(xs, ys, meta=None):
    if meta is None:
        return " ".join(f"({x},{y})" for x, y in zip(xs, ys))
    return " ".join(f"({x},{y}) [{m}]" for x, y, m in zip(xs, ys, meta))


def group(n, body, hsep="1.5cm"):
    return (r"\begin{tikzpicture}" "\n"
            r"\begin{groupplot}[group style={group size=" f"{n} by 1, horizontal sep={hsep}"
            r"}, " + COMMON + "]\n" + body.rstrip() + "\n"
            r"\end{groupplot}" "\n" r"\end{tikzpicture}")


# ---------------------------------------------------------------- Fig 1: the corpus
def fig_corpus():
    s, d30 = J("m31s_depth_share.json"), J("m30_selection_audit.json")
    h = s["depth_histogram"]
    ks = sorted(int(k) for k in h)
    vs = [h[str(k)] for k in ks]

    seg = {k: [] for k in ("lo", "mid", "hi")}
    for key in ("P_model_ViennaRNA", "P_neural_RibonanzaNet"):
        dd = d30["D"][key]
        seg["lo"].append(100 * dd["frac_below_0.08"])
        seg["mid"].append(100 * dd["frac_between"])
        seg["hi"].append(100 * dd["frac_above_0.99"])

    body = rf"""\nextgroupplot[width=5.6cm, height=3.6cm, ybar, bar width=9pt,
    xlabel={{helix depth of the flipped pair}}, ylabel={{interventions}},
    xtick={{{",".join(map(str, ks))}}}, ymin=0, ymax={max(vs)*1.24:.0f},
    enlarge x limits=0.10, nodes near coords, every node near coord/.append style={{font=\tiny,
    color=nmink}}, title={{a}}]
\addplot[fill={FREE}, draw=none] coordinates {{{co(ks, vs)}}};

\nextgroupplot[width=4.9cm, height=3.6cm, xbar stacked, bar width=13pt,
    xmin=0, xmax=100, xlabel={{share of interventions (\%)}},
    ytick={{0,1}}, yticklabels={{ViennaRNA, RibonanzaNet}}, y dir=reverse,
    enlarge y limits=0.55, legend columns=3,
    legend style={{at={{(0.5,-0.52)}}, anchor=north, font=\scriptsize, draw=none,
      /tikz/every even column/.append style={{column sep=4pt}}}},
    title={{b}}]
\addplot[fill={GREY}, draw=none] coordinates {{({seg['lo'][0]:.1f},0) ({seg['lo'][1]:.1f},1)}};
\addlegendentry{{$<0.08$}}
\addplot[fill={MID}, draw=none] coordinates {{({seg['mid'][0]:.1f},0) ({seg['mid'][1]:.1f},1)}};
\addlegendentry{{between}}
\addplot[fill={INK}, draw=none] coordinates {{({seg['hi'][0]:.1f},0) ({seg['hi'][1]:.1f},1)}};
\addlegendentry{{$>0.99$}}"""
    emit("fig1_corpus.tex", group(2, body, hsep="1.9cm"))


# ---------------------------------------------------------------- Fig 2: calibration
def fig_calibration():
    v = J("m26_model_scored.json")["D4"]["bins"]
    n = J("m26c_neural_scored.json")["N3"]["bins"]
    parts = []
    for bins, col, name, letter, first in ((v, THM, "ViennaRNA", "a", True),
                                           (n, NEU, "RibonanzaNet", "b", False)):
        xs = list(range(1, len(bins) + 1))
        ys = [f"{b['rf_mean']:.4f}" for b in bins]
        meta = [f"$P${{=}}{b['p_mean']:.3g}" for b in bins]
        ylab = "ylabel={mean measured rescue}," if first else ""
        parts.append(rf"""\nextgroupplot[width=5.3cm, height=3.7cm,
    xlabel={{bin of the predictor's own pair probability}}, {ylab}
    xtick={{{",".join(map(str, xs))}}}, enlarge x limits=0.14, enlarge y limits=0.42,
    nodes near coords, point meta=explicit symbolic,
    every node near coord/.append style={{font=\tiny, color=nmink, below=4pt}},
    title={{{letter}}}]
\addplot[color={col}, mark=*, mark size=1.7pt, line width=1.0pt]
  coordinates {{{co(xs, ys, meta)}}};""")
    emit("fig2_calibration.tex", group(2, "\n\n".join(parts), hsep="2.3cm"))


