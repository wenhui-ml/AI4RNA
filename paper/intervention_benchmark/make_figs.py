#!/usr/bin/env python3
"""Display items for the intervention-benchmark manuscript, emitted as TikZ/pgfplots.

Each figure is written as a .tex fragment the manuscript \\input{}s, so the figures are native
vector graphics in the document's own fonts. The numbers inside them are still generated: every
coordinate below comes from a committed run artifact, exactly as \\jdg{} does for the prose.
Nothing is recomputed here -- when a curve is needed and no artifact holds it, the run that
produces it is written and committed first, which is why m31t_recovery_curve.json exists.
"""
from __future__ import annotations

import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
CEIL = os.path.abspath(os.path.join(HERE, "..", "..", "rna_harness", "runs", "ceiling"))
FIGS = os.path.join(HERE, "figs")
os.makedirs(FIGS, exist_ok=True)

NEU, THM, FREE, INK, GREY, MID = ("nmneural", "nmthermo", "nmfree", "nmink", "nmgrey", "nmmid")

COMMON = r"""axis lines=left, axis line style={line width=0.4pt},
    tick style={line width=0.4pt, color=nmgrey}, tick align=outside,
    label style={font=\footnotesize}, tick label style={font=\scriptsize},
    legend style={font=\scriptsize, draw=none, fill=none},
    title style={font=\footnotesize\bfseries, at={(0,1.02)}, anchor=south west}"""


def J(n):
    return json.load(open(os.path.join(CEIL, n)))


def emit(name, body):
    with open(os.path.join(FIGS, name), "w") as fh:
        fh.write("% GENERATED by make_figs.py from rna_harness/runs/ceiling/*.json.\n"
                 "% Do not edit: every coordinate below comes from a committed run artifact.\n")
        fh.write(body.rstrip() + "\n")
    print(f"  wrote figs/{name}")


def co(xs, ys, meta=None):
    if meta is None:
        return " ".join(f"({x},{y})" for x, y in zip(xs, ys))
    return " ".join(f"({x},{y}) [{m}]" for x, y, m in zip(xs, ys, meta))


def group(n, body, hsep="1.5cm"):
    return (r"\begin{tikzpicture}" "\n"
            r"\begin{groupplot}[group style={group size=" f"{n} by 1, horizontal sep={hsep}"
            r"}, " + COMMON + "]\n" + body.rstrip() + "\n"
            r"\end{groupplot}" "\n" r"\end{tikzpicture}")


# ---------------------------------------------------------------- Fig 1: the corpus
def fig_corpus():
    s, d30 = J("m31s_depth_share.json"), J("m30_selection_audit.json")
    h = s["depth_histogram"]
    ks = sorted(int(k) for k in h)
    vs = [h[str(k)] for k in ks]

    seg = {k: [] for k in ("lo", "mid", "hi")}
    for key in ("P_model_ViennaRNA", "P_neural_RibonanzaNet"):
        dd = d30["D"][key]
        seg["lo"].append(100 * dd["frac_below_0.08"])
        seg["mid"].append(100 * dd["frac_between"])
        seg["hi"].append(100 * dd["frac_above_0.99"])

    body = rf"""\nextgroupplot[width=5.6cm, height=3.6cm, ybar, bar width=9pt,
    xlabel={{helix depth of the flipped pair}}, ylabel={{interventions}},
    xtick={{{",".join(map(str, ks))}}}, ymin=0, ymax={max(vs)*1.24:.0f},
    enlarge x limits=0.10, nodes near coords, every node near coord/.append style={{font=\tiny,
    color=nmink}}, title={{a\quad what the criterion admitted}}]
\addplot[fill={FREE}, draw=none] coordinates {{{co(ks, vs)}}};

\nextgroupplot[width=4.9cm, height=3.6cm, xbar stacked, bar width=13pt,
    xmin=0, xmax=100, xlabel={{share of interventions (\%)}},
    ytick={{0,1}}, yticklabels={{ViennaRNA, RibonanzaNet}}, y dir=reverse,
    enlarge y limits=0.55, legend columns=3,
    legend style={{at={{(0.5,-0.34)}}, anchor=north, font=\scriptsize, draw=none,
      /tikz/every even column/.append style={{column sep=4pt}}}},
    title={{b\quad neither score is saturated}}]
\addplot[fill={GREY}, draw=none] coordinates {{({seg['lo'][0]:.1f},0) ({seg['lo'][1]:.1f},1)}};
\addlegendentry{{$<0.08$}}
\addplot[fill={MID}, draw=none] coordinates {{({seg['mid'][0]:.1f},0) ({seg['mid'][1]:.1f},1)}};
\addlegendentry{{between}}
\addplot[fill={INK}, draw=none] coordinates {{({seg['hi'][0]:.1f},0) ({seg['hi'][1]:.1f},1)}};
\addlegendentry{{$>0.99$}}"""
    emit("fig1_corpus.tex", group(2, body))


# ---------------------------------------------------------------- Fig 2: calibration
def fig_calibration():
    v = J("m26_model_scored.json")["D4"]["bins"]
    n = J("m26c_neural_scored.json")["N3"]["bins"]
    parts = []
    for bins, col, name, letter, first in ((v, THM, "ViennaRNA", "a", True),
                                           (n, NEU, "RibonanzaNet", "b", False)):
        xs = list(range(1, len(bins) + 1))
        ys = [f"{b['rf_mean']:.4f}" for b in bins]
        meta = [f"$P${{=}}{b['p_mean']:.3g}" for b in bins]
        ylab = "ylabel={mean measured rescue}," if first else ""
        parts.append(rf"""\nextgroupplot[width=5.3cm, height=3.7cm,
    xlabel={{bin of the predictor's own pair probability}}, {ylab}
    xtick={{{",".join(map(str, xs))}}}, enlarge x limits=0.14, enlarge y limits=0.42,
    nodes near coords, point meta=explicit symbolic,
    every node near coord/.append style={{font=\tiny, color=nmink, below=4pt}},
    title={{{letter}\quad {name}}}]
\addplot[color={col}, mark=*, mark size=1.7pt, line width=1.0pt]
  coordinates {{{co(xs, ys, meta)}}};""")
    emit("fig2_calibration.tex", group(2, "\n\n".join(parts)))


# ---------------------------------------------------------------- Fig 3: Claim 3
def fig_ranking():
    m31, m31r, t = (J("m31_which_flips_rescue.json"), J("m31r_review.json"),
                    J("m31t_recovery_curve.json"))
    A = m31["A_within_design"]
    rows = [("RibonanzaNet", A["P_neural"], NEU),
            ("helix depth (free)", A["depth_baseline"], FREE),
            ("ViennaRNA", A["P_vienna"], THM)]
    lines = []
    for i, (_lab, r, c) in enumerate(rows):
        y = len(rows) - i
        lines.append(rf"\addplot[color={c}, line width=1.6pt, forget plot] "
                     rf"coordinates {{({r['ci'][0]},{y}) ({r['ci'][1]},{y})}};")
        lines.append(rf"\addplot[color={c}, mark=*, mark size=2pt, only marks, forget plot] "
                     rf"coordinates {{({r['rho']},{y})}};")
    sw = m31["B_auroc_sweep"]
    th = [r["threshold"] for r in sw]
    f = [f"{100*x:.0f}" for x in t["fracs"]]
    c = t["curves"]

    body = rf"""\nextgroupplot[width=4.5cm, height=3.4cm,
    xlabel={{within-design rank agreement $\rho$}},
    ytick={{{",".join(str(len(rows)-i) for i in range(len(rows)))}}},
    yticklabels={{{",".join(r[0] for r in rows)}}},
    yticklabel style={{font=\tiny}}, ymin=0.4, ymax={len(rows)+0.6},
    extra x ticks={{0}}, extra x tick style={{grid=major,
      grid style={{densely dotted, color={GREY}}}, xticklabel=\empty}},
    title={{a\quad a free integer ties the best model}}]
{chr(10).join(lines)}

\nextgroupplot[width=4.15cm, height=3.4cm,
    xlabel={{rescue threshold defining a hit}}, ylabel={{within-cell AUROC}},
    legend pos=south west, enlarge y limits=0.20,
    title={{b\quad and overtakes them}}]
\addplot[color={NEU}, mark=*, mark size=1.3pt, line width=0.9pt]
  coordinates {{{co(th, [r["P_neural"] for r in sw])}}};
\addlegendentry{{RibonanzaNet}}
\addplot[color={FREE}, mark=square*, mark size=1.3pt, line width=0.9pt]
  coordinates {{{co(th, [r["depth_baseline"] for r in sw])}}};
\addlegendentry{{helix depth}}
\addplot[color={THM}, mark=triangle*, mark size=1.6pt, line width=0.9pt]
  coordinates {{{co(th, [r["P_vienna"] for r in sw])}}};
\addlegendentry{{ViennaRNA}}

\nextgroupplot[width=4.15cm, height=3.4cm,
    xlabel={{share of a design's flips built (\%)}},
    ylabel={{rescuing flips recovered (\%)}}, legend pos=south east,
    title={{c\quad what it is worth in constructs}}]
\addplot[color={NEU}, line width=1.1pt]
  coordinates {{{co(f, [f"{100*y:.3f}" for y in c["depth_then_P_neural"]])}}};
\addlegendentry{{depth, ties broken by model}}
\addplot[color={FREE}, line width=1.1pt]
  coordinates {{{co(f, [f"{100*y:.3f}" for y in c["depth_only"]])}}};
\addlegendentry{{depth alone}}
\addplot[color={GREY}, dashed, line width=0.9pt]
  coordinates {{{co(f, [f"{100*y:.3f}" for y in c["random"]])}}};
\addlegendentry{{random}}"""
    emit("fig3_ranking.tex", group(3, body, hsep="1.15cm"))


# ---------------------------------------------------------------- Fig 4: the two audits
def fig_audits():
    d, s = J("m26d_clean_subset.json"), J("m30_selection_audit.json")
    arms, xs = ["all", "clean", "leaked"], [1, 2, 3]
    bars = []
    for mdl, col in (("RibonanzaNet", NEU), ("ViennaRNA", THM)):
        ys = [f"{d['arms'][f'{mdl}_{a}']['slope']:.5f}" for a in arms]
        bars.append(rf"\addplot[fill={col}, draw=none] coordinates {{{co(xs, ys)}}};"
                    "\n" rf"\addlegendentry{{{mdl}}}")
    tl = ",".join("{" + t + "}" for t in
                  (rf"all\\$n${{=}}{d['arms']['ViennaRNA_all']['n']}",
                   rf"excised\\$n${{=}}{d['n_clean']}",
                   rf"leaked\\$n${{=}}{d['n_dirty']}"))
    S3 = s["S3"]
    est = [("whole corpus", S3["full"], None, INK),
           ("passes cutoff", S3["pass"], S3["ci_pass"], GREY),
           ("filter did not bind", S3["fallback"], S3["ci_fallback"], FREE)]
    lines = []
    for i, (_l, e, cc, col) in enumerate(est):
        y = len(est) - i
        if cc:
            lines.append(rf"\addplot[color={col}, line width=1.6pt, forget plot] "
                         rf"coordinates {{({cc[0]},{y}) ({cc[1]},{y})}};")
        lines.append(rf"\addplot[color={col}, mark=*, mark size=2pt, only marks, forget plot] "
                     rf"coordinates {{({e},{y})}};")

    body = rf"""\nextgroupplot[width=5.4cm, height=3.5cm, ybar, bar width=10pt,
    xtick={{1,2,3}}, xticklabels={{{tl}}},
    xticklabel style={{align=center, font=\tiny}},
    ylabel={{within-stratum skill slope}}, enlarge x limits=0.24, ymin=0,
    legend pos=north east, title={{a\quad leakage audit}}]
{chr(10).join(bars)}

\nextgroupplot[width=4.9cm, height=3.5cm,
    xlabel={{matched G--C $-$ A--U contrast in rescue}},
    ytick={{{",".join(str(len(est)-i) for i in range(len(est)))}}},
    yticklabels={{{",".join("{" + e[0] + "}" for e in est)}}},
    yticklabel style={{font=\tiny}}, ymin=0.4, ymax={len(est)+0.6},
    extra x ticks={{0}}, extra x tick style={{grid=major,
      grid style={{densely dotted, color={GREY}}}, xticklabel=\empty}},
    title={{b\quad selection audit}}]
{chr(10).join(lines)}"""
    emit("fig4_audits.tex", group(2, body))


if __name__ == "__main__":
    print("emitting TikZ display items")
    ok = True
    for fn in (fig_corpus, fig_calibration, fig_ranking, fig_audits):
        try:
            fn()
        except FileNotFoundError as e:
            print(f"  SKIP {fn.__name__}: missing artifact {e.filename}"); ok = False
    print("done" if ok else "done (some artifacts missing)")
