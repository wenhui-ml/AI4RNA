def design(target, seed=0):
    rng = random.Random(seed)
    n = len(target)
    wanted = set(target_pairs(target))

    if n == 0:
        return ""

    pairs = sorted((min(i, j), max(i, j)) for i, j in wanted)
    partner = {}
    for i, j in pairs:
        partner[i] = j
        partner[j] = i

    units = []
    unit_of = {}
    for i, j in pairs:
        unit_of[i] = len(units)
        unit_of[j] = len(units)
        units.append((i, j))
    for i in range(n):
        if i not in partner:
            unit_of[i] = len(units)
            units.append((i,))

    canonical = (("G", "C"), ("C", "G"), ("A", "U"), ("U", "A"))
    all_pair_types = canonical + (("G", "U"), ("U", "G"))

    def crosses(p, q):
        a, b = p
        c, d = q
        return (a < c < b < d) or (c < a < d < b)

    def is_nested(ps):
        ps = list(ps)
        for x in range(len(ps)):
            for y in range(x + 1, len(ps)):
                if crosses(ps[x], ps[y]):
                    return False
        return True

    def nested_db(ps):
        out = ["."] * n
        for i, j in ps:
            out[i] = "("
            out[j] = ")"
        return "".join(out)

    # Bracket alphabets usually encode the target's crossing stem families.
    families = {}
    for p in pairs:
        families.setdefault(target[p[0]], []).append(p)
    family_lists = list(families.values())

    projections = []
    projection_seen = set()

    def add_projection(ps):
        ps = frozenset(ps)
        if ps not in projection_seen and is_nested(ps):
            projection_seen.add(ps)
            projections.append(ps)

    if is_nested(pairs):
        add_projection(pairs)

    for f in family_lists:
        add_projection(f)

    # Enumerate compatible combinations of bracket families.
    if len(family_lists) <= 7:
        combinations = []
        for mask in range(1, 1 << len(family_lists)):
            ps = []
            for k in range(len(family_lists)):
                if mask & (1 << k):
                    ps.extend(family_lists[k])
            if is_nested(ps):
                combinations.append(ps)
        combinations.sort(key=lambda x: -len(x))
        for ps in combinations[:8]:
            add_projection(ps)

    # Additional maximal nested projections independent of bracket notation.
    for mode in range(8):
        order = list(pairs)
        if mode == 0:
            order.sort(key=lambda p: (p[1] - p[0], p[0]))
        elif mode == 1:
            order.sort(key=lambda p: (-(p[1] - p[0]), p[0]))
        elif mode == 2:
            order.sort()
        elif mode == 3:
            order.sort(reverse=True)
        else:
            rng.shuffle(order)
        selected = []
        for p in order:
            if all(not crosses(p, q) for q in selected):
                selected.append(p)
        add_projection(selected)

    if not projections:
        add_projection([])

    pair_rank = {}
    for fam in family_lists:
        fam = sorted(fam)
        for k, p in enumerate(fam):
            pair_rank[p] = k

    def compatible_from_raw(raw, projection, style):
        if raw is None or len(raw) != n:
            raw = rand_seq(n, rng.randrange(1 << 30))
        s = list(raw)
        for i in range(n):
            if s[i] not in "ACGU":
                s[i] = "ACGU"[rng.randrange(4)]

        for k, (i, j) in enumerate(pairs):
            current = (s[i], s[j])
            if (i, j) in projection and current in all_pair_types:
                continue

            rank = pair_rank.get((i, j), k)
            if style == 0:
                choice = (rank + k) % 4
            elif style == 1:
                choice = (2 * rank + k + 1) % 4
            elif style == 2:
                choice = (rank // 2 + k) & 1
            else:
                choice = rng.randrange(4)
            s[i], s[j] = canonical[choice]
        return "".join(s)

    starts = []
    start_seen = set()

    def add_start(seq):
        if (seq is not None and len(seq) == n and
                all(c in "ACGU" for c in seq) and seq not in start_seen):
            start_seen.add(seq)
            starts.append(seq)

    # Inverse-fold the strongest nested views of the pseudoknot.
    for k, projection in enumerate(projections[:8]):
        raw = inverse_fold_cf(
            nested_db(projection),
            seed=(seed * 1000003 + k * 9176 + 41) & 0x7fffffff
        )
        add_start(compatible_from_raw(raw, projection, k % 3))

    # Fully compatible patterned sequences provide useful independent basins.
    for style in range(5):
        if style < 4:
            s = ["A" if ((i + style) & 1) == 0 else "C" for i in range(n)]
        else:
            s = list(rand_seq(
                n, (seed * 65537 + style * 104729 + 73) & 0x7fffffff
            ))
        for k, (i, j) in enumerate(pairs):
            rank = pair_rank.get((i, j), k)
            if style == 0:
                t = (rank + k) % 4
            elif style == 1:
                t = (2 * rank + k + 1) % 4
            elif style == 2:
                t = (rank // 2 + k) & 1
            elif style == 3:
                t = 2 + ((rank + k) & 1)
            else:
                t = rng.randrange(4)
            s[i], s[j] = canonical[t]
        add_start("".join(s))

    cache = {}
    evaluations = [0]
    solved = [None]

    def evaluate(seq):
        old = cache.get(seq)
        if old is not None:
            return old

        pk = set(fold_pkiss_pairs(seq))
        pr = set(fold_probknot_pairs(seq))
        evaluations[0] += 1

        if pk == wanted and pr == wanted:
            solved[0] = seq

        miss_pk = wanted - pk
        miss_pr = wanted - pr
        extra_pk = pk - wanted
        extra_pr = pr - wanted

        total = (len(miss_pk) + len(miss_pr) +
                 len(extra_pk) + len(extra_pr))
        worst = max(len(miss_pk) + len(extra_pk),
                    len(miss_pr) + len(extra_pr))
        disagreement = len(pk ^ pr)
        missing = len(miss_pk) + len(miss_pr)
        extra = len(extra_pk) + len(extra_pr)

        energy = (12 * total + 4 * worst + 2 * disagreement +
                  2 * missing + extra)
        result = (energy, total, worst, disagreement,
                  miss_pk, miss_pr, extra_pk, extra_pr)
        cache[seq] = result
        return result

